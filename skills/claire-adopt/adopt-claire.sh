  note_skipped "$rel"
else
  mkdir -p "$(dirname "$DST/$rel")"
  awk '/^### II-/ { skip = 1 } skip && /^---$/ { skip = 0 } !skip' \
    "$SRC/$rel" > "$DST/$rel"
  note_copied "$rel (entries stripped)"
fi

