copy_file() {
  local rel="$1"
  if [[ -e "$DST/$rel" ]]; then
    note_skipped "$rel"
  else
    mkdir -p "$(dirname "$DST/$rel")"
    cp "$SRC/$rel" "$DST/$rel"
    note_copied "$rel"
  fi
}

echo "Copying CLAIRE framework files from $SRC to $DST"

for path in "${COPY_PATHS[@]}"; do
  if [[ -d "$SRC/$path" ]]; then
    while IFS= read -r -d '' f; do
      copy_file "${f#"$SRC/"}"
    done < <(find "$SRC/$path" -type f -print0 | sort -z)
  elif [[ -f "$SRC/$path" ]]; then
    copy_file "$path"
  else
    echo "ERROR: missing in source: $path" >&2
    exit 1
  fi
done

# intent-insights.md: copy with this repo's accumulated entries stripped.
