elif [[ -f "$SRC/$rel" ]]; then
  mkdir -p "$(dirname "$DST/$rel")"
  grep -E '^[[:space:]]*(#|$)' "$SRC/$rel" > "$DST/$rel"
  note_copied "$rel (rows stripped)"
